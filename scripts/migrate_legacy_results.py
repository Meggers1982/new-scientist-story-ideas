"""One-time back-conversion of the previous pipeline's JSON archive into the
markdown digest format this pipeline uses.

The repo previously accumulated every screened study in a single
`data/results.json` (kept at `archive/legacy-results.json`). Only studies
published in the LOOKBACK_DAYS window before the cutover are converted — older
entries are past their pitch window and would just pad the dashboard, but they
stay in the archive file rather than being deleted.

Legacy entries are grouped by the run date they were found on, one digest file
per run, mirroring what the live pipeline produces. They carry no
trends/continuity section and no per-study fact-check verdicts, because the old
pipeline never generated those; the fields render as "—" rather than being
faked. Each converted file is stamped so it is obvious in the dashboard that it
came from the old pipeline.

Run once:

    python3 scripts/migrate_legacy_results.py

Re-running is safe — existing output files are skipped, not overwritten.
"""

import json
import re
from datetime import datetime, timedelta
from pathlib import Path

REPO_ROOT = Path(__file__).parent.parent
ARCHIVE_PATH = REPO_ROOT / "archive" / "legacy-results.json"
OUTPUTS_DIR = REPO_ROOT / "outputs"
SEEN_PMIDS_PATH = REPO_ROOT / "seen_pmids.json"

LOOKBACK_DAYS = 60
JOURNAL_COUNT = 325
PUBDATE_FORMATS = ("%Y %b %d", "%Y %b", "%Y")


def _parse_pubdate(raw: str):
    raw = (raw or "").strip()
    for fmt in PUBDATE_FORMATS:
        try:
            return datetime.strptime(raw, fmt)
        except ValueError:
            continue
    return None


def _novelty(study: dict) -> str:
    """Map the old free-text `groundbreaking` field onto the new fixed labels."""
    text = (study.get("groundbreaking") or "").lower()
    for needle, label in (
        ("counterintuitive", "Counterintuitive"),
        ("overturn", "Overturns prior research"),
        ("first-in-class", "First-in-class"),
        ("first", "First-in-class"),
        ("replicat", "Failed replication"),
        ("mechanism", "New mechanism"),
    ):
        if needle in text:
            return label
    return study.get("groundbreaking") or "Not classified"


def _pitch_angle(study: dict) -> str:
    """Flatten the old nested `ns_pitch` object into one prose angle."""
    pitch = study.get("ns_pitch") or {}
    parts = []
    if pitch.get("headline"):
        parts.append(f'Proposed headline — "{pitch["headline"]}"')
    if pitch.get("hook"):
        parts.append(pitch["hook"])
    if pitch.get("pitch_angle"):
        parts.append(pitch["pitch_angle"])
    if pitch.get("why_it_fits"):
        parts.append(f'Why it fits: {pitch["why_it_fits"]}')
    return " ".join(parts) or "—"


def _caveats(study: dict) -> str:
    caveats = (study.get("caveats") or "").strip()
    extra = (study.get("ns_pitch") or {}).get("caveats_to_flag") or ""
    if extra and extra.strip().lower() not in caveats.lower():
        caveats = f"{caveats}. {extra}".strip(". ") if caveats else extra
    return caveats or "None recorded"


def _entry(number: int, study: dict) -> str:
    score = study.get("ns_score")
    ns_fit = (
        f"{score}/10 — {study.get('ns_score_reason', '').strip()}"
        if score
        else "Not scored by the previous pipeline"
    )
    fact_note = (study.get("fact_check_note") or "").strip()
    return "\n".join([
        f"### {number}. {study.get('headline', 'Untitled')}",
        "",
        f"**Journal:** *{study.get('journal', 'Unknown')}* | **Published:** {study.get('pubdate', '')}",
        f"**PMID:** {study.get('pmid', '')} | **DOI:** {study.get('doi') or 'Not available'}",
        f"**Novelty:** {_novelty(study)}",
        f"**NS fit:** {ns_fit}",
        f"**Media check:** {study.get('media_coverage', 'Not verified')}",
        "",
        f"**The study:** {study.get('summary', '—')}",
        "",
        f"**Why it matters:** {study.get('why_it_matters', '—')}",
        "",
        "**Story angles:**",
        f"- **Pitch angle:** {_pitch_angle(study)}",
        "- **Wider angle:** Not generated by the previous pipeline.",
        "",
        f"**Caveats:** {_caveats(study)}"
        + (f" *Editor's fact-check note: {fact_note}*" if fact_note else ""),
        "",
        "---",
        "",
    ])


def _digest_markdown(run_date: str, studies: list[dict]) -> str:
    header = "\n".join([
        "# New Scientist Story Ideas",
        f"**Run date:** {run_date} | **Coverage window:** Last 7 days",
        f"**Journals searched:** {JOURNAL_COUNT} | **Articles screened:** {len(studies)}",
        "**Focus:** Broad (all mind and brain topics)",
        "**Publication:** New Scientist | **Section:** New Scientist Mind",
        "**Source:** Converted from the previous JSON pipeline — no trends section "
        "or per-study fact-check verdict was generated for these runs.",
    ]) + "\n\n---\n\n"

    entries = "".join(_entry(i, s) for i, s in enumerate(studies, start=1))

    citations = ["## Citation Reference", "", "| # | PMID | Journal | Date | DOI |", "|---|------|---------|------|-----|"]
    for i, s in enumerate(studies, start=1):
        citations.append(
            f"| {i} | {s.get('pmid', '')} | {s.get('journal', '')} | "
            f"{s.get('pubdate', '')} | {s.get('doi') or 'Not available'} |"
        )

    return header + entries + "\n".join(citations) + "\n"


def main() -> None:
    if not ARCHIVE_PATH.exists():
        raise SystemExit(f"No archive found at {ARCHIVE_PATH.relative_to(REPO_ROOT)}")

    archive = json.loads(ARCHIVE_PATH.read_text(encoding="utf-8"))
    all_studies = archive.get("studies", [])
    cutoff = datetime.now() - timedelta(days=LOOKBACK_DAYS)

    recent = []
    for study in all_studies:
        published = _parse_pubdate(study.get("pubdate", ""))
        if published and published >= cutoff:
            recent.append(study)

    print(
        f"{len(all_studies)} studies in archive; {len(recent)} published since "
        f"{cutoff:%Y-%m-%d} ({LOOKBACK_DAYS}-day window)"
    )

    by_run: dict[str, list[dict]] = {}
    for study in recent:
        run_date = (study.get("run_date") or "")[:10] or "undated"
        by_run.setdefault(run_date, []).append(study)

    OUTPUTS_DIR.mkdir(exist_ok=True)
    written = 0
    skipped = 0
    seen_pmids: set[str] = set()

    for run_date in sorted(by_run):
        studies = sorted(by_run[run_date], key=lambda s: -(s.get("ns_score") or 0))
        seen_pmids.update(s["pmid"] for s in studies if s.get("pmid"))

        path = OUTPUTS_DIR / f"New Scientist Story Ideas — Archive — {run_date}.md"
        if path.exists():
            skipped += 1
            continue
        path.write_text(_digest_markdown(run_date, studies), encoding="utf-8")
        written += 1

    # Seed the dedup ledger so the live pipeline never re-pitches a converted study.
    existing: set[str] = set()
    if SEEN_PMIDS_PATH.exists():
        existing = set(json.loads(SEEN_PMIDS_PATH.read_text()).get("pmids", []))
    # Every PMID the old pipeline ever wrote up is off the table, not just the
    # converted ones — the point of the ledger is "already pitched", and that
    # was true of the older entries too.
    existing |= {s["pmid"] for s in all_studies if s.get("pmid")}
    SEEN_PMIDS_PATH.write_text(
        json.dumps(
            {"updated": datetime.now().strftime("%Y-%m-%d"), "pmids": sorted(existing)},
            indent=2,
        ),
        encoding="utf-8",
    )

    print(f"Wrote {written} digest file(s) to outputs/" + (f", skipped {skipped} existing" if skipped else ""))
    print(f"Seeded seen_pmids.json with {len(existing)} PMIDs")


if __name__ == "__main__":
    main()
